#!/usr/bin/env bash
# =============================================================================
# SYNAPSE — Raspberry Pi One-Command Setup Script
# =============================================================================
# Usage:
#   sudo bash deploy/scripts/setup_pi.sh [NODE_ID] [BROADCAST_IP]
#
# Examples:
#   sudo bash deploy/scripts/setup_pi.sh SYNAPSE-001 192.168.10.255
#   sudo bash deploy/scripts/setup_pi.sh SYNAPSE-002 192.168.10.255
#
# Requirements:
#   - Raspberry Pi OS (Bullseye or Bookworm) with Python 3.10+
#   - Run as root (sudo)
# =============================================================================

set -euo pipefail

# ── Arguments ────────────────────────────────────────────────────────────────
NODE_ID="${1:-SYNAPSE-001}"
BROADCAST_IP="${2:-192.168.10.255}"
INSTALL_DIR="/opt/synapse"
DATA_DIR="/var/lib/synapse/data"
KEYS_DIR="/etc/synapse/keys"
LOG_DIR="/var/log/synapse"
ENV_FILE="/etc/synapse/node.env"
SERVICE_FILE="/etc/systemd/system/synapse-node.service"

echo "============================================================"
echo " SYNAPSE Edge Node Setup"
echo " Node ID   : ${NODE_ID}"
echo " Broadcast : ${BROADCAST_IP}"
echo " Install   : ${INSTALL_DIR}"
echo "============================================================"

# ── 1. System check ──────────────────────────────────────────────────────────
if [ "$EUID" -ne 0 ]; then
    echo "[ERROR] Please run as root: sudo bash deploy/scripts/setup_pi.sh"
    exit 1
fi

PYTHON=$(command -v python3.11 || command -v python3.10 || command -v python3 || true)
if [ -z "$PYTHON" ]; then
    echo "[ERROR] Python 3.10+ is required but not found."
    exit 1
fi

PY_VER=$($PYTHON -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
echo "[+] Using Python ${PY_VER} at ${PYTHON}"

# Check Python version >= 3.10
$PYTHON -c "import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)" || {
    echo "[ERROR] Python 3.10+ required. Found ${PY_VER}."
    exit 1
}

# ── 2. Install system packages ───────────────────────────────────────────────
echo "[+] Updating package lists and installing system dependencies..."
apt-get update -qq
apt-get install -y --no-install-recommends \
    python3-pip \
    python3-venv \
    libsodium-dev \
    libffi-dev \
    libssl-dev \
    sqlite3 \
    2>/dev/null

# ── 3. Create directories ────────────────────────────────────────────────────
echo "[+] Creating runtime directories..."
mkdir -p "${INSTALL_DIR}/var/run"
mkdir -p "${DATA_DIR}"
mkdir -p "${KEYS_DIR}"
mkdir -p "${LOG_DIR}"
mkdir -p /etc/synapse

# ── 4. Copy project files ────────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

echo "[+] Copying project files from ${PROJECT_ROOT} to ${INSTALL_DIR}..."
rsync -a --exclude='.git' --exclude='*.pyc' --exclude='__pycache__' \
    --exclude='.pytest_cache' --exclude='var/' --exclude='*.ps1' \
    "${PROJECT_ROOT}/" "${INSTALL_DIR}/"

# ── 5. Install Python dependencies ───────────────────────────────────────────
echo "[+] Installing Python dependencies..."
$PYTHON -m pip install --upgrade pip --quiet
$PYTHON -m pip install -r "${INSTALL_DIR}/requirements.txt" --quiet

# ── 6. Write node environment file ───────────────────────────────────────────
if [ ! -f "${ENV_FILE}" ]; then
    echo "[+] Writing node configuration to ${ENV_FILE}..."
    cat > "${ENV_FILE}" << EOF
# SYNAPSE Node Environment — auto-generated by setup_pi.sh
SYNAPSE_NODE_ID=${NODE_ID}
SYNAPSE_COMM_PORT=5000
SYNAPSE_DISCOVERY_PORT=5999
SYNAPSE_API_PORT=8080
SYNAPSE_BROADCAST_IP=${BROADCAST_IP}
SYNAPSE_LOG_LEVEL=INFO
SYNAPSE_DATA_DIR=${DATA_DIR}
SYNAPSE_KEYS_DIR=${KEYS_DIR}
EOF
else
    echo "[~] ${ENV_FILE} already exists — skipping (edit manually to change config)"
fi

# ── 7. Pre-generate cryptographic keys ───────────────────────────────────────
echo "[+] Pre-generating cryptographic keys for [${NODE_ID}]..."
$PYTHON "${INSTALL_DIR}/deploy/scripts/provision_keys.py" \
    --node-id "${NODE_ID}" \
    --keys-dir "${KEYS_DIR}" || echo "[~] Key generation skipped (may already exist)"

# ── 8. Fix ownership ─────────────────────────────────────────────────────────
echo "[+] Setting directory ownership for user 'pi'..."
chown -R pi:pi "${INSTALL_DIR}" "${DATA_DIR}" "${LOG_DIR}"
chown -R root:pi "${KEYS_DIR}"
chmod 750 "${KEYS_DIR}"

# ── 9. Install systemd service ───────────────────────────────────────────────
echo "[+] Installing systemd service..."
cp "${INSTALL_DIR}/deploy/systemd/synapse-node.service" "${SERVICE_FILE}"
# Patch the service file with the correct NODE_ID and broadcast IP
sed -i "s/SYNAPSE_NODE_ID=.*/SYNAPSE_NODE_ID=${NODE_ID}/" "${SERVICE_FILE}"
sed -i "s/SYNAPSE_BROADCAST_IP=.*/SYNAPSE_BROADCAST_IP=${BROADCAST_IP}/" "${SERVICE_FILE}"

systemctl daemon-reload
systemctl enable synapse-node.service

echo ""
echo "============================================================"
echo " SYNAPSE setup complete for node [${NODE_ID}]"
echo ""
echo " Configuration : ${ENV_FILE}"
echo " Keys          : ${KEYS_DIR}"
echo " Data          : ${DATA_DIR}"
echo " Logs          : journalctl -u synapse-node -f"
echo ""
echo " Start  : sudo systemctl start synapse-node"
echo " Status : sudo systemctl status synapse-node"
echo " Stop   : sudo systemctl stop synapse-node"
echo " API    : http://<this-pi-ip>:8080/api/status"
echo "============================================================"
